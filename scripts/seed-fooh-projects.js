async function run() {
  console.log('Clearing old improvement projects in settings for Fooh Hospital...')
  const { data: oldRows } = await supabase.from('settings').select('key, value').like('key', 'improvement_project:%')
  if (oldRows && oldRows.length > 0) {
    for (const r of oldRows) {
      try {
        const val = JSON.parse(r.value)
        if (val.hospital_id === hospitalId) {
          await supabase.from('settings').delete().eq('key', r.key)
          console.log(`Deleted old project: ${r.key}`)
        }
      } catch (e) {
        // ignore
      }
    }
  }

  console.log('Inserting 3 flagship benchmark projects for Fooh Hospital...')
  for (const p of projects) {
    await supabase.from('settings').insert({
      key: `improvement_project:${p.id}`,
      value: JSON.stringify(p)
    })
    console.log(`✓ Inserted: [${p.department_name}] ${p.title}`)
    console.log(`  Lead: ${p.project_lead}`)
    console.log(`  Goal: ${p.smart_goal}`)
  }

  console.log('Done! 3 world-class clinical benchmark projects successfully seeded into settings.')
}

run().catch(console.error)
